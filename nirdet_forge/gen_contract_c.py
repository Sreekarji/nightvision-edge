"""
gen_contract_c.py — nirdet_pp.c is GENERATED, not maintained
=============================================================
    python gen_contract_c.py --emit      # write nirdet_pp.c
    python gen_contract_c.py --check     # exit 1 if the file on disk is stale
    python gen_contract_c.py --print     # to stdout

WHY THIS EXISTS
---------------
Six decoders implement the NIRDet decode contract. Five of them `import
config`. nirdet_pp.c cannot, so until now it was kept in step by a grep test
(test_decode_contract T1) that could only prove FOUR #defines matched. It
could not prove that the DECODE BODY matched, and in fact it did not: the C
filtered degenerate boxes on the PRE-clamp extent and applied max_det as a
pre-NMS heap capacity. Both are contract violations that no test could see.

Parity is now BY CONSTRUCTION. The constants and the membership body are
rendered from config.py. `--check` is called by test_decode_contract T8, so a
config.py edit that is not followed by `--emit` fails the gate tests.

THE STAMP IS NOT deploy_contract()['hash']
------------------------------------------
deploy_contract() folds in CLAHE settings and a flat-field file digest, which
are DATASET properties: two profiles produce two different hashes for the same
C source. The stamp below covers only the frozen decode/membership constants,
which is exactly the set this file renders. Mixing the two would make
nirdet_pp.c churn on every profile change.

Pure stdlib plus `import config` (numpy). No torch, no new dependencies.
"""

