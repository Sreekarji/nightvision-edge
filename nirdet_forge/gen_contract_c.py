# ---------------------------------------------------------------------------
# render / check
# ---------------------------------------------------------------------------

def render() -> str:
    vals = contract_values()
    stamp = contract_stamp(vals)
    src = _TEMPLATE
    src = src.replace("@@BANNER@@", BANNER)
    src = src.replace("@@STAMP@@", stamp)
    for name in ("DECODE_OFFSET_SCALE", "DECODE_OFFSET_BIAS",
                 "REG_LOG_CLAMP_MIN", "REG_LOG_CLAMP_MAX",
                 "NIRDET_MIN_BOX_PX"):
        src = src.replace(f"@@{name}@@", _cf(vals[name]))
    for name in ("NIRDET_NUM_CLASSES", "NIRDET_MAX_LEVELS", "NIRDET_MAX_DET"):
        src = src.replace(f"@@{name}@@", str(int(vals[name])))
    if "@@" in src:
        leftover = src[src.index("@@"):src.index("@@") + 40]
        raise AssertionError(f"unsubstituted placeholder near: {leftover!r}")
    return src


def check(path: str = C_PATH) -> tuple:
    """-> (ok, human-readable report). Used by test_decode_contract.py T8."""
    want = render()
    if not os.path.isfile(path):
        return False, f"{path} does not exist; run gen_contract_c.py --emit"
    with open(path, "r", encoding="utf-8", newline="") as fh:
        got = fh.read()
    if got == want:
        return True, f"{os.path.basename(path)} matches config.py " \
                     f"(stamp {contract_stamp(contract_values())})"
    diff = list(difflib.unified_diff(
        got.splitlines(True), want.splitlines(True),
        fromfile="on disk", tofile="generated", n=2))
    head = "".join(diff[:60])
    return False, (f"{os.path.basename(path)} is STALE relative to config.py. "
                   f"Run: python gen_contract_c.py --emit\n{head}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--emit", action="store_true", help="write nirdet_pp.c")
    g.add_argument("--check", action="store_true", help="exit 1 if stale")
    g.add_argument("--print", dest="to_stdout", action="store_true")
    ap.add_argument("--out", default=C_PATH)
    args = ap.parse_args(argv)

    if args.to_stdout:
        sys.stdout.write(render())
        return 0
    if args.check:
        ok, report = check(args.out)
        print(("[gen] " if ok else "[gen] FAIL ") + report)
        return 0 if ok else 1

    src = render()
    # newline="" so the file is byte-identical on Windows and Linux; --check
    # compares bytes and a CRLF translation would fail the gate on one OS.
    with open(args.out, "w", encoding="utf-8", newline="") as fh:
        fh.write(src)
    print(f"[gen] wrote {args.out} ({len(src)} bytes, "
          f"stamp {contract_stamp(contract_values())})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
