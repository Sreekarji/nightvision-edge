def contract_stamp(vals: dict) -> str:
    """Deterministic 16-hex digest over the injected values only.

    No timestamp, no hostname, no path: two machines with the same config.py
    must produce byte-identical C, or --check is useless in CI.
    """
    blob = ";".join(f"{k}={vals[k]!r}" for k in sorted(vals))
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


def _cf(v: float) -> str:
    """Render a float as a C float literal that round-trips exactly."""
    return f"{float(v)!r}f"


